public class Escape {
    static void main(String[] args) {
        System.out.println("Hello \"Satyam\"...."); //insert a double quote
        System.out.println("Hello \'Satyam\'...."); //insert a single quote
        System.out.println("Hello \n Satyam....");  //insert a next line
        System.out.println("Hello \\ Satyam \\...."); // insert a backslash in the character
    }
}
